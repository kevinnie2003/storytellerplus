import Foundation

func teamCN(_ team: String) -> String {
  switch team {
  case "townsfolk": return "镇民"
  case "outsider": return "外来者"
  case "minion": return "爪牙"
  case "demon": return "恶魔"
  case "traveler": return "旅行者"
  case "fabled": return "传奇角色"
  default: return team
  }
}

/// 当前游戏的快照，交给 AI 当上下文
struct AIGameContext {
  var playName: String = ""
  var gameState: Int = 0
  var playableCharacters: [Character] = []
  var players: [Character] = []
  var alive: [Bool] = []
  var deathVote: [Bool] = []
  var playerTags: [[Reminder]] = []
  var globalTags: [Reminder] = []
  var bluffs: [Character] = []
  var fabled: [Character] = []
  var jinxes: [Jinx] = []
  var logs: [GameLogEntry] = []
  var allReminders: [Reminder] = []
  var setupNotes: String = ""
}

enum AIPrompts {
  
  // MARK: 整理上下文
  
  /// 剧本里的角色列表（不含旅行者）
  static func scriptText(_ characters: [Character], includeTravelers: Bool = false) -> String {
    var lines: [String] = []
    for team in ["townsfolk", "outsider", "minion", "demon", "traveler"] {
      if team == "traveler" && !includeTravelers {
        continue
      }
      let list = characters.filter({ $0.team == team })
      if list.isEmpty {
        continue
      }
      lines.append("【\(teamCN(team))】")
      for c in list {
        lines.append("- \(c.name)\(c.setup ? "（影响配置）" : "")：\(c.ability)")
      }
    }
    return lines.joined(separator: "\n")
  }
  
  /// 当前剧本里出现的角色各自的带法提示
  static func characterTipsSection(_ characters: [Character]) -> String {
    let text = AIStorytellerKnowledge.tipsText(for: characters)
    if text.isEmpty {
      return ""
    }
    return """


    【这个剧本里部分角色的带法提示】
    下面是按官方版本的能力整理的说书人经验。如果剧本改过某个角色的能力，以剧本里的能力文字为准。
    \(text)
    """
  }
  
  static func standardCounts(_ playerCount: Int) -> String {
    let n = min(max(playerCount, 5), 15)
    let c = teamCounts[n] ?? [0, 0, 0, 0, 0]
    return "镇民 \(c[0])、外来者 \(c[1])、爪牙 \(c[2])、恶魔 \(c[3])"
  }
  
  static func seatingText(_ ctx: AIGameContext) -> String {
    var lines: [String] = []
    for (i, c) in ctx.players.enumerated() {
      var line = "\(i + 1)号：\(c.name.isEmpty ? "未分配" : c.name)"
      if !c.team.isEmpty {
        line += "（\(teamCN(c.team))）"
      }
      if i < ctx.alive.count && ctx.gameState != 0 {
        if ctx.alive[i] {
          line += " 存活"
        } else {
          let hasVote = i < ctx.deathVote.count ? ctx.deathVote[i] : true
          line += " 死亡\(hasVote ? "" : "，已用掉死人票")"
        }
      }
      if i < ctx.playerTags.count && !ctx.playerTags[i].isEmpty {
        let tags = ctx.playerTags[i].map({ "\($0.from)·\($0.effect)\($0.isReversed ? "(倒置)" : "")" }).joined(separator: "、")
        line += " 标记：\(tags)"
      }
      lines.append(line)
    }
    return lines.joined(separator: "\n")
  }
  
  static func phaseText(_ ctx: AIGameContext) -> String {
    let day = ctx.logs.filter({ $0.type == 10 }).count
    switch ctx.gameState {
    case 0: return "配版中，游戏还没开始"
    case 1: return "首个夜晚"
    case 2: return "第 \(max(day, 1)) 个白天"
    case 3: return "第 \(day + 1) 个夜晚"
    default: return "未知"
    }
  }
  
  static func grimoireText(_ ctx: AIGameContext) -> String {
    var parts: [String] = []
    parts.append("剧本：\(ctx.playName)")
    parts.append("当前阶段：\(phaseText(ctx))")
    parts.append("座位顺序（环形，最后一位和 1 号相邻）：\n\(seatingText(ctx))")
    let bluffs = ctx.bluffs.filter({ !$0.name.isEmpty }).map({ $0.name })
    if !bluffs.isEmpty {
      parts.append("恶魔伪装：\(bluffs.joined(separator: "、"))")
    }
    if !ctx.globalTags.isEmpty {
      parts.append("全局标记：\(ctx.globalTags.map({ "\($0.from)·\($0.effect)" }).joined(separator: "、"))")
    }
    if !ctx.fabled.isEmpty {
      parts.append("传奇角色：\(ctx.fabled.map({ "\($0.name)（\($0.ability)）" }).joined(separator: "；"))")
    }
    if !ctx.jinxes.isEmpty {
      parts.append("相克和特殊规则：\n\(ctx.jinxes.map({ "- \($0.name)：\($0.description)" }).joined(separator: "\n"))")
    }
    return parts.joined(separator: "\n\n")
  }
  
  // MARK: 说书人心法（三个功能共用）
  
  /// 高水平说书人的通用原则，整理自官方百科、集石百科的说书人建议和社区的带局经验
  static let storytellerCraft = """
  【说书人的基本原则】
  - 规则不能破。没有醉酒、中毒、误判的玩家必须拿到真信息；阵营人数、角色能力照剧本文字执行。玩家要能信任自己拿到的信息，输赢才有意义。
  - 说书人的自由只在规则留出的口子里：醉酒中毒玩家的假信息、陌客和间谍这类角色的误判、能力文字里写着“可能”“说书人决定”的地方、首夜信息位里“另一名玩家”选谁。
  - 每个选择先过一遍第零原则：这是为了玩家的乐趣，还是说书人自己觉得好玩。优先级是好玩、有趣、平衡。
  - 说书人是讲故事的人，不是裁判。邪恶方人少、信息少，从开局就处在劣势，说书人不配合他们的伪装，他们没法打。
  - 帮弱不帮强，而且只用小而隐蔽的方式，帮完要经得起双方复盘时的追问。例：善良方太顺时，让醉酒的共情者拿到错误数字；邪恶方太顺时，让他这晚恰好拿到正确数字。
  - 判断不出哪边弱时，不帮，或者略偏邪恶。善良方只需要对一次，邪恶方每天都要过关。对邪恶的额外帮助随着游戏推进递减，一旦邪恶占优立刻停手；对善良的帮助给出去就收不回来，还会滚雪球，所以前期尤其要省着给。
  - 同一个动作在不同阶段方向相反。例：猎手开枪打死被当作恶魔的陌客，十几人存活时是帮邪恶，只剩四人时反而替善良确认了两个好人。做决定前先数存活人数。
  - 不要给出能把某个人百分之百钉死的信息。这个游戏的设计是善良方最多推到九成把握，最后一天通常是二选一，被指控的人要有辩解空间。
  - 不要让说书人的选择直接决定胜负，也不要让任何玩家进入“已经注定输、只能坐等结束”的状态。
  - 让玩家自己做选择，不要引导恶魔的刀，不要暗示玩家该选谁。展示信息时不要犹豫，或者每次都同样地停顿，不让停顿变成线索。
  - 说书人自己出了错，承认有错但不说是什么，然后继续，不要靠暗中偏帮另一边来补偿。
  - 节奏本身是平衡工具。白天拖得越长善良方越占便宜，最后一天不要搞轮流发言。

  【假信息怎么给】
  - 首要原则是维持幻觉。醉酒中毒的玩家应该自己慢慢推出“我的信息有问题”，而不是说书人用一条荒唐的信息直接告诉他。
  - 假信息分“难解”和“死路”。难解的假信息能和场上的声明、邪恶方的伪装、恶魔伪装里的角色对上，玩家会认真拿去推理。死路信息一看就知道自己坏了，要避免，例如：共情者拿到 3、厨师的数字超出这局可能的上限、邻座没变而共情者的数字变了、把玩家自己放进“两人之一”、展示机制上不可能在场的角色、一串毫无规律的数字。
  - 前期先给真的或者符合预期的信息，后面关键的那条假信息才立得住。不重要的信息给真的，关键信息再作假。醉酒中毒不必每次都错。
  - 数字类只偏一点（真 1 给 0 或 2）。指向玩家的假信息，指向邪恶方希望被怀疑的善良玩家，或者洗白正被怀疑的邪恶玩家，不要随机指。
  - 前后要一致。同一个玩家几晚的信息连起来要讲得通，不要今天指东明天指西。
  - 常用的可信做法：送葬者醉酒中毒时，被处决者自称的身份已经被全场相信就给那张牌，或者给酒鬼、陌客、间谍这类解释得通的牌；守鸦人中毒时给邪恶玩家正在伪装的角色；“两人之一”类的首夜信息位，展示一个不爱声张的角色（守鸦人、士兵这类）配两个都不是的人；占卜师中毒时让“是”的组合比“否”少。
  - 要给得像，先得知道邪恶方在装什么。不清楚时建议说书人夜里单独问，或者白天私聊问。

  【误判：陌客、间谍这类】
  - 每次被探查都单独决定，默认用来帮邪恶，但一个昼夜一两次就够，不必每次触发。
  - 选一个方向并坚持，频繁切换没人信。同一局里不要既让陌客被调查员当爪牙、又被占卜师当恶魔，会被反向验证。
  - 陌客整局至少要坑善良方一次，一个全程对善良有利、还被全场相信的陌客等于没在运作。间谍被送葬者、守鸦人看到时给善良角色，优先给他正在伪装的那个。
  - 不要把陌客当成恶魔来给游戏续命，不要让陌客接到恶魔的传位，不要在爪牙和恶魔互认的环节使用误判。

  【需要说书人自己编内容的能力】
  判断标准：这个能力的乐趣在哪，给出的内容要服务于这个乐趣；有趣的信息胜过正确但没用的信息。
  - 博学者这类“一真一假两条信息”：
    - 目标不只是一真一假，而是让博学者想去相信错的那条。假的那条要贴合邪恶方正在讲的故事，所以先看邪恶方在装什么、在推谁。
    - 宽泛的陈述好过狭窄的。狭窄的一旦是假的就毫无用处，宽泛的即使是假的也能帮玩家排除一种布局。
    - 分阶段给。第一二天给能引出讨论的：隐藏的角色、邻座关系、三人小组。第三四天把范围收窄，让它和邪恶方的说法发生碰撞。最后一两天可以给强信息，但任何时候都不直接点出恶魔，也不要让信息硬确认博学者自己是好人。
    - 好的句式：“X 号、Y 号、Z 号里恰好有一名邪恶玩家”“恶魔和一名外来者相邻”“恰好有一名外来者和爪牙相邻”“两名爪牙相邻”或“不相邻”“你的两位邻座阵营不同”“连续坐在一起的镇民最多有 N 人”“首夜恰好有 N 个角色因为自己的能力醒来”“某三个角色里恰好有 N 个在场”“X 号和 Y 号是同一阵营”“某角色不在场”；后期可以用“X 号要么是最初的恶魔，要么是好人”。
    - 坏的句式：一句话定身份的（“几号是某角色”“几号是邪恶”）；博学者不可能合理知道的夜间细节（“某角色昨晚选了几号”）；直接点名别的角色会拿到什么（“厨师会得到 1”，应改成“恰好有两名邪恶玩家相邻”）；“某角色是恶魔伪装”（应改成“某角色不在场”）；别的信息角色的弱化版。
    - 剧本里有会改变外来者数量、让全场信息为假、或者制造疯狂的角色时，不要给能直接验出它们在不在场的信息，比如外来者数量、首日有没有人醉酒中毒、场上有没有疯狂角色，否则博学者就成了检测器。
    - 措辞要精确。“所有爪牙都在这三人里”和“这三人都是爪牙”完全不同；一条信息是假的，不代表它的反面是真的。每天换一种类型。
    - 博学者自己醉酒中毒时，给两条真的或者两条假的。
  - 失忆者这类“说书人设计能力”：能力以拿信息为主，强度可以比普通镇民略高，因为他要花几天才能猜出来。每晚都要有可感知的反馈，并且让他做的选择能产生不同的数据。可以挂在角色类型、座位、提名、投票、谁在说谎这些钩子上，例如“每晚指两人，得知其中有没有爪牙”“每晚得知存活邻座里的镇民数”。他猜能力时按意思判断，分无关、有关、接近、猜中四档，措辞不同也算对。对他的猜测永远说真话，醉酒中毒只影响能力产出的信息。
  - 灵言师这类“秘密词语”：词必须是闲聊和盘逻辑时绝对不会无意说出的生僻词，可以自创。乐趣在于灵言师冒着暴露的风险私下策反，而不是有人聊着聊着被转了阵营。常用词、口头禅、游戏术语、流行语都不行。要具体、少见、好念好记、说书人隔着桌子也能听清，比如冷门地名、古怪的专有名词、生造的组合词（官方举的例子是“君士坦丁堡”“廷巴克图”这种）。
  - 艺术家这类“问说书人一个问题”：只答是、不是、不知道。真的无法判断才答不知道，问题有歧义就请他重问。
  - 渔夫这类“向说书人要建议”：给“该做什么”，不给“是什么”。建议要可执行，例如“让声称是外来者的那名玩家活着”，不能是“恶魔是几号”。醉酒中毒时给听上去合理但对善良无益的建议。
  - 将军这类“哪边占优”：看存活人数、善良方掌握的信息量和可信度、邪恶方伪装的质量、下一个可能被处决的是谁。拿不准给平手。醉酒中毒时不要简单反过来，给一条连贯的假走势。
  - 女祭司这类“说书人指一个人”：不要指向信息最强的人，那等于替善良解题。指向需要被信任的人、刚发生怪事的人、跟着邪恶投票的好人、快被错杀的好人。
  - 疯狂的判定：看他有没有尽力，不看效果。如果他合理地还能做更多来让全场相信、却没做，就不算疯狂；只说一句、只私聊、加一堆限定词、私下暗示自己被影响了，都不够。处决不是强制的，惩罚不隔夜追究。新手从宽，老手从严，尺度最好开局前就告诉玩家。

  【说书人决定的死亡和转移】
  - 镇长被刀时：默认让镇长活到最后一天更有戏；如果全场很早就认定他是镇长，就让他正常死，给邪恶机会。要转移就转给一个能死的人，不要转给死人、士兵、被保护的人造成没人死，那等于让邪恶白丢一个夜晚。一局最多用一两次。弱势一方需要帮助时可以转到爪牙身上，但不要转给恶魔或关键信息位，不要用它结束游戏。
  - 修补匠这类“随时可能死”：绝不在会让游戏结束的时候杀。夜里死比白天死有趣，因为分不清死因，适合用来掩护邪恶方的击杀或支持他们的伪装。
  - 造谣者这类“说对了就有人死”：陈述要全场听清、可判真假才算。死的人优先选握有重要信息的、或者能戳穿邪恶伪装的；不要杀恶魔，不要选死不了的人。
  - 和平主义者这类“可能不死”：一局触发一次左右，越是后期的关键节点越值得救；善良已经大幅领先时可以一次都不救。救下来会坐实邪恶玩家的伪装时不要救。
  - 其他写着“说书人选择”“可能”的能力：先想清楚这个选择会让哪一方得利、会不会直接定胜负，再按平衡原则选。

  【残局】
  - 目标是把游戏带到胜负未定的最后一天。邪恶已经明显占优时，照常配合他们的操作，但不要再额外送东西。
  - 只有一方确定获胜才提前结束。邪恶存活人数过半、甚至控制了投票，也不能直接宣布结束，只要还有活着的好人能提名、死人票还在，就还有翻盘的可能。
  - 最后一夜和最后一天，不要用说书人裁量的死亡或误判去改变结果。
  """
  
