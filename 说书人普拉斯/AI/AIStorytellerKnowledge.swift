  static func tip(for name: String) -> String? {
    let key = name.trimmingCharacters(in: .whitespacesAndNewlines)
    if let tip = tips[key] {
      return tip
    }
    if let official = aliases[key] {
      return tips[official]
    }
    return nil
  }
  
  /// 给定剧本里的角色，拼出带法提示文字。没有任何匹配时返回空字符串。
  static func tipsText(for characters: [Character]) -> String {
    var seen = Set<String>()
    var lines: [String] = []
    for character in characters {
      if seen.contains(character.name) {
        continue
      }
      seen.insert(character.name)
      if let tip = tip(for: character.name) {
        lines.append("- \(character.name)：\(tip)")
      }
    }
    return lines.joined(separator: "\n")
  }
